/**
 * 파이프라인 에디터 — 출력 선택 목록에서 자동 생성 임시 데이터셋(TEMP) 제외 (WD-224)
 *
 * 결함: 출력 Select 에 다른 파이프라인 스텝이 만든 「(자동생성)」 임시 데이터셋이 그대로 나와, 고르면 두 파이프라인이 실행마다 서로의 결과를
 * 덮어썼다. 출력 목록에서는 TEMP 를 빼고, 입력 목록(다른 스텝의 결과를 읽기)에서는 그대로 보여야 한다. 이미 남의 TEMP 로 고정된
 * 스텝(레거시)은 트리거가 빈 칸이 되지 않게 현재 값만 남기고 무엇을 바꿔야 하는지 안내한다.
 */

import type { Page } from '@playwright/test';

import { createDataset } from '../../factories/dataset.factory';
import { createPipelineDetail, createStep } from '../../factories/pipeline.factory';
import { createPageResponse, mockApi } from '../../fixtures/api-mock';
import { expect, test } from '../../fixtures/auth.fixture';
import { grantPipelinePermissions } from '../../fixtures/pipeline.fixture';

/** 다른 파이프라인 스텝이 만든 TEMP */
const FOREIGN_TEMP_ID = 90;
const FOREIGN_TEMP_NAME = '다른 파이프라인 > 추출 (자동생성)';
/** 이 스텝 자신의 TEMP — 목록에는 없다(자동 생성 표시만) */
const OWN_TEMP_ID = 91;
const SCREENSHOT_DIR = 'test-results/tc/pipeline-temp-output';

async function setupMocks(page: Page, outputDatasetId: number | null) {
  const step = createStep({
    id: 5,
    name: '쓰기',
    scriptContent: 'SELECT 1 AS v',
    loadStrategy: 'REPLACE',
    // null = 자동 생성 스텝 — 서버 응답처럼 자기 TEMP id(91)를 채우고 outputAutoGenerated 로 알린다(WD-222).
    outputDatasetId: outputDatasetId ?? OWN_TEMP_ID,
    outputAutoGenerated: outputDatasetId == null,
    outputDatasetName: outputDatasetId === FOREIGN_TEMP_ID ? FOREIGN_TEMP_NAME : '쓰기 (자동생성)',
    inputDatasetIds: [],
  });
  await mockApi(page, 'GET', '/api/v1/pipelines/1', createPipelineDetail({ id: 1, steps: [step] }));
  await mockApi(page, 'GET', '/api/v1/pipelines/1/executions', []);
  await mockApi(page, 'GET', '/api/v1/pipelines/1/triggers', []);
  await mockApi(page, 'GET', '/api/v1/pipelines/1/trigger-events', []);
  await mockApi(
    page,
    'GET',
    '/api/v1/datasets',
    createPageResponse([
      createDataset({ id: 1, name: '공개 데이터셋', tableName: 'pub' }),
      createDataset({ id: FOREIGN_TEMP_ID, name: FOREIGN_TEMP_NAME, tableName: 'ptmp_9_extract', originType: 'TEMP' }),
    ]),
  );
  await mockApi(page, 'GET', `/api/v1/datasets/${FOREIGN_TEMP_ID}`, {
    ...createDataset({ id: FOREIGN_TEMP_ID, name: FOREIGN_TEMP_NAME, tableName: 'ptmp_9_extract', originType: 'TEMP' }),
    columns: [],
  });
}

async function openStep(page: Page) {
  await page.goto('/pipelines/1');
  await page.getByRole('button', { name: '수정' }).click();
  await page.locator('.react-flow__node').first().click();
}

test.describe('파이프라인 에디터 — 출력 목록의 자동 생성 임시 데이터셋 (WD-224)', () => {
  test.beforeEach(async ({ authenticatedPage: page }) => {
    await grantPipelinePermissions(page);
  });

  test('출력 목록에는 「(자동생성)」 TEMP 가 없고, 입력 목록에는 남아 있다', async ({ authenticatedPage: page }) => {
    await setupMocks(page, null);
    await openStep(page);

    const outputSelect = page.getByRole('combobox', { name: '출력 데이터셋' });
    await outputSelect.click();
    const listbox = page.getByRole('listbox');
    await expect(listbox.getByRole('option', { name: '공개 데이터셋' })).toBeVisible();
    await expect(listbox.getByRole('option', { name: '자동 생성 (임시)' })).toBeVisible();
    await expect(listbox.getByText('(자동생성)')).toHaveCount(0);
    await page.screenshot({ path: `${SCREENSHOT_DIR}/output-list-without-temp.png` });
    await page.keyboard.press('Escape');

    // 입력 목록은 같은 데이터셋 목록을 그대로 쓴다 — 다른 스텝의 결과를 입력으로 읽는 것은 허용
    await page.getByRole('combobox', { name: '입력 데이터셋' }).click();
    await expect(page.getByRole('option', { name: new RegExp('\\(자동생성\\)') })).toBeVisible();
  });

  test('이미 남의 TEMP 로 고정된 출력은 현재 값을 보이고 바꿀 방법을 안내한다', async ({ authenticatedPage: page }) => {
    await setupMocks(page, FOREIGN_TEMP_ID);
    await openStep(page);

    const outputSelect = page.getByRole('combobox', { name: '출력 데이터셋' });
    await expect(outputSelect).toHaveText(FOREIGN_TEMP_NAME);
    const help = page.getByTestId('output-foreign-temp-help');
    await expect(help).toContainText('다른 스텝이 자동으로 만든 임시 데이터셋은 출력으로 지정할 수 없습니다');
    const helpId = await help.getAttribute('id');
    expect(await outputSelect.getAttribute('aria-describedby')).toContain(helpId!);

    // 자동 생성으로 바꾸면 안내가 사라지고, 목록에서도 TEMP 가 빠진다
    await outputSelect.click();
    await page.getByRole('option', { name: '자동 생성 (임시)' }).click();
    await expect(help).toHaveCount(0);
    await outputSelect.click();
    await expect(page.getByRole('listbox').getByText('(자동생성)')).toHaveCount(0);
  });
});
