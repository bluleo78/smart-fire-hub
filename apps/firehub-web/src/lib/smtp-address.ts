/**
 * SMTP 발신자 주소의 표기 판정(#728).
 *
 * 서버(`SettingsService` 의 `SMTP_SENDER_SYNTAX`)와 **글자 그대로 같은 문법**이어야 한다 — 한쪽만
 * 넓으면 "칸 검증은 통과하고 저장은 400"(#727) 이 다시 생긴다. 아래 정규식 조각은 서버의
 * `SMTP_ATOM`·`SMTP_DOTTED`·`SMTP_ADDR` 와 1:1 이다.
 *
 * 받는 형태는 발송 코드가 From 으로 받는 형태다: `주소` 또는 `표시명 <주소>` 하나.
 * 회원가입 폼의 이메일 규칙(`z.email`)을 그대로 쓰지 않는 이유는 그 규칙이 `표시명 <주소>` 를
 * 거부하기 때문이다 — 발송 코드는 그 형태를 받으므로 막으면 과잉 차단이다.
 *
 * - 주소: 점으로 이은 토막 `@` 점으로 이은 토막. 도메인에 점을 요구하지 않는다 — 사내 릴레이에서는
 *   `alerts@mailhost` 가 합법적인 발신자다.
 * - 표시명: 특수문자(`<>()[]\,;:"@`)가 없는 글자들이거나, 큰따옴표로 감싼 문자열. 쉼표·괄호가 든
 *   표시명은 따옴표로 감싸야 한다 — 메일 주소 파서가 따옴표 없는 쉼표를 주소 구분자로, 괄호를
 *   주석으로 읽는다.
 */

/** 주소의 한 토막 — 공백·`@`·점과 특수문자가 없는 글자들. */
const ATOM = String.raw`[^\s@<>()\[\]\\,;:".]+`;
/** 점으로 이은 토막들 — 점이 맨 앞·맨 뒤에 오거나 연달아 오지 않는다. */
const DOTTED = String.raw`${ATOM}(?:\.${ATOM})*`;
/** `로컬@도메인`. */
const ADDR = `${DOTTED}@${DOTTED}`;
const SENDER_SYNTAX = new RegExp(
  String.raw`^(?:${ADDR}|(?:"[^"\\]*"\s*|[^<>()\[\]\\,;:"@]*)<${ADDR}>)$`,
);

/** `주소` 또는 `표시명 <주소>` 하나인가. 앞뒤 공백이 있으면 아니다(호출부가 다듬어 넘긴다). */
export function isSenderAddressSyntax(raw: string): boolean {
  return raw === raw.trim() && SENDER_SYNTAX.test(raw);
}
