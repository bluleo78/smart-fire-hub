/**
 * SMTP 발신자 주소의 표기 판정(#728).
 *
 * 서버(`SettingsService.validateSmtpFromAddress`)와 **같은 문법**이어야 한다 — 한쪽만 넓으면
 * "검증은 통과하고 저장은 400"(#727) 이 다시 생긴다.
 *
 * 받는 형태는 발송 코드가 From 으로 받는 형태와 같다: `주소` 또는 `표시명 <주소>` 하나.
 * 회원가입 폼의 이메일 규칙(`z.email`)을 그대로 쓰지 않는 이유는 그 규칙이 `표시명 <주소>` 를
 * 거부하기 때문이다 — 발송 코드는 그 형태를 받으므로 막으면 과잉 차단이다.
 *
 * 주소 부분은 `로컬@도메인`(공백·꺾쇠·두 번째 `@` 없음)이다. 도메인에 점을 요구하지 않는다 —
 * 사내 릴레이에서는 `alerts@mailhost` 가 합법적인 발신자다.
 *
 * 표시명 안의 문자는 여기서 따지지 않는다(쉼표가 든 표시명은 따옴표로 감싸야 하는 등 규칙이
 * 파서의 영역이다). 그런 값은 서버가 거부하고, 저장 실패 토스트가 서버 사유를 그대로 보여준다.
 */
export function isSenderAddressSyntax(raw: string): boolean {
  // `표시명 <주소>` 면 꺾쇠 안을, 아니면 전체를 주소로 본다.
  const bracketed = /^[^<>]*<([^<>]*)>$/.exec(raw);
  const address = bracketed ? bracketed[1] : raw;
  return /^[^\s@<>]+@[^\s@<>]+$/.test(address);
}
