/**
 * SMTP 호스트·발신자 주소의 표기 판정(#728).
 *
 * 서버(`SettingsService` 의 `SMTP_*` 조각)와 **글자 그대로 같은 문법**이어야 한다 — 한쪽만 넓으면
 * "칸 검증은 통과하고 저장은 400"(#727) 이 다시 생긴다. 실제로 두 번 어긋났다:
 *   1) 서버만 메일 주소 파서를 더 돌려 도메인의 `_`·`?`·`。` 를 서버만 거부했다.
 *   2) `\s`·`trim()` 이 언어마다 다른 문자를 공백으로 봐 NBSP·BOM 을 서버만 통과시켰다.
 * 그래서 이 문법은 `\s`·`\p{..}` 같은 **엔진이 뜻을 정하는 클래스를 쓰지 않고** 코드 단위를 명시한
 * 범위만 쓴다(`u` 플래그도 쓰지 않는다 — 서버 정규식과 같은 UTF-16 단위 판정). 두 구현의 일치는
 * 두 앱이 함께 읽는 픽스처(`firehub-api/src/test/resources/fixtures/smtp-validation-vectors.json`)가
 * 지킨다. 아래 조각을 고치면 서버의 같은 이름 조각과 픽스처를 함께 고쳐야 한다.
 *
 * 받는 형태는 발송 코드가 From 으로 받는 형태다: `주소` 또는 `표시명 <주소>` 하나.
 * 회원가입 폼의 이메일 규칙(`z.email`)을 그대로 쓰지 않는 이유는 그 규칙이 `표시명 <주소>` 를
 * 거부하기 때문이다 — 발송 코드는 그 형태를 받으므로 막으면 과잉 차단이다.
 *
 * - 로컬 파트: 점으로 이은 토막. 한글 등 비ASCII 글자는 받는다.
 * - 도메인: 점으로 이은 ASCII 글자·숫자·하이픈 토막. 점을 요구하지 않는다 — 사내 릴레이에서는
 *   `alerts@mailhost` 가 합법적인 발신자다. `_`·`?`·전각 마침표 등은 서버의 발송 파서가 거부하므로
 *   여기서 막는다. 한글 도메인은 퓨니코드(`xn--…`)로 적는다.
 * - 표시명: 특수문자(`<>()[]\,;:"@`)가 없는 글자들이거나, 큰따옴표로 감싼 문자열. 쉼표·괄호가 든
 *   표시명은 따옴표로 감싸야 한다 — 메일 주소 파서가 따옴표 없는 쉼표를 주소 구분자로, 괄호를
 *   주석으로 읽는다. 공백은 ASCII 공백만 받는다(줄바꿈·탭·보이지 않는 문자는 헤더를 깨뜨린다).
 * - 맨 앞은 공백이 아니다(호출부가 다듬어 넘긴다). 맨 뒤는 문법상 공백일 수 없다.
 */

/**
 * 공백·제어문자·보이지 않는 문자. C0·C1 제어문자와 DEL, 유니코드 공백(U+00A0·U+1680·U+2000~200A·
 * U+2028·U+2029·U+202F·U+205F·U+3000), 폭 없는 문자·방향 제어·BOM(U+00AD·U+061C·U+180E·
 * U+200B~200F·U+202A~202E·U+2060~206F·U+FEFF·U+FFF9~FFFB), 한글 채움 문자(U+115F·U+1160·U+3164·
 * U+FFA0). ASCII 공백(U+0020)은 `BLANK` 에만 들어 있다.
 */
const INVISIBLE =
  String.raw`\u0000-\u001F\u007F-\u00A0\u00AD\u061C\u115F\u1160\u1680\u180E\u2000-\u200F\u2028-\u202F\u205F-\u206F\u3000\u3164\uFEFF\uFFA0\uFFF9-\uFFFB`;
/** `INVISIBLE` 에 ASCII 공백을 더한 것 — 호스트와 주소에는 하나도 올 수 없다. */
const BLANK = String.raw`\u0020${INVISIBLE}`;
/** 로컬 파트의 한 토막 — 공백류·`@`·점과 특수문자가 없는 글자들. */
const ATOM = String.raw`[^${BLANK}@<>()\[\]\\,;:".]+`;
/** 도메인의 한 토막 — ASCII 글자·숫자·하이픈만. */
const LABEL = String.raw`[A-Za-z0-9-]+`;
/** `로컬@도메인`. 점이 맨 앞·맨 뒤에 오거나 연달아 오지 않는다. */
const ADDR = String.raw`${ATOM}(?:\.${ATOM})*@${LABEL}(?:\.${LABEL})*`;
const SENDER_SYNTAX = new RegExp(
  String.raw`^(?! )(?:${ADDR}|(?:"[^${INVISIBLE}"\\]*" *|[^${INVISIBLE}<>()\[\]\\,;:"@]*)<${ADDR}>)$`,
);
const HOST_SYNTAX = new RegExp(`^[^${BLANK}]+$`);

/** `주소` 또는 `표시명 <주소>` 하나인가. 앞뒤 공백이 있으면 아니다(호출부가 다듬어 넘긴다). */
export function isSenderAddressSyntax(raw: string): boolean {
  return SENDER_SYNTAX.test(raw);
}

/**
 * 호스트 표기인가 — 비어 있지 않고 공백·제어문자·보이지 않는 문자가 하나도 없다.
 * `/\s/` 로 판정하지 않는 이유: 폭 없는 공백(U+200B) 같은 문자는 `\s` 가 아니라서 칸을 통과한 뒤
 * 서버에서 거부되거나, 저장된 뒤 발송 시점의 DNS 실패로만 드러난다.
 */
export function isSmtpHostSyntax(raw: string): boolean {
  return HOST_SYNTAX.test(raw);
}
