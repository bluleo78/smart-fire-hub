-- WD-488 PoC: 일반 DDL(테이블·인덱스·시퀀스·뷰) — clean 이 지울 객체 종류를 고루 만든다.
CREATE TABLE poc_item (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  active NUMBER(1) DEFAULT 1 NOT NULL,
  payload JSON,
  created_at TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE INDEX idx_poc_item_name ON poc_item (name);
CREATE SEQUENCE poc_seq START WITH 1;
CREATE VIEW poc_item_active AS SELECT id, name FROM poc_item WHERE active = 1;
INSERT INTO poc_item (name, payload) VALUES ('seed', '{"k":1}');
-- 자기 스키마 FK — clean 이 CASCADE CONSTRAINTS 없이 FK 를 먼저 떼고 지우는지 본다.
CREATE TABLE poc_child (id NUMBER PRIMARY KEY, item_id NUMBER NOT NULL REFERENCES poc_item (id));
