  /** 알려진 Instant 를 여러 바인딩으로 TIMESTAMP 에 넣고, 여러 방식으로 읽어 같은지 본다(JVM 시간대: 결과에 표시). */
  @Test
  void timestampUtcRoundTrip() {
    Instant known = Instant.parse("2026-11-04T01:02:03.456Z");
    report("jvm_timezone", java.util.TimeZone.getDefault().getID());
    probe(
        "timestamp",
        c -> {
          Object[][] binds = {
            {"setObject(OffsetDateTime UTC)", known.atOffset(ZoneOffset.UTC)},
            {"setObject(LocalDateTime UTC wall)", LocalDateTime.ofInstant(known, ZoneOffset.UTC)},
            {"setTimestamp(Timestamp.from)", Timestamp.from(known)},
          };
          for (Object[] b : binds) {
            try {
              try (PreparedStatement ps =
                  c.prepareStatement("UPDATE probe_t SET ts = ? WHERE v = 2")) {
                if (b[1] instanceof Timestamp t) ps.setTimestamp(1, t);
                else ps.setObject(1, b[1]);
                ps.executeUpdate();
              }
              try (Statement st = c.createStatement();
                  ResultSet rs =
                      st.executeQuery(
                          "SELECT ts, TO_CHAR(ts, 'YYYY-MM-DD HH24:MI:SS.FF3') FROM probe_t WHERE v = 2")) {
                rs.next();
                Instant viaTs = rs.getTimestamp(1).toInstant();
                String stored = rs.getString(2);
                String viaLdt;
                try {
                  viaLdt = String.valueOf(rs.getObject(1, LocalDateTime.class));
                } catch (SQLException | RuntimeException e) {
                  viaLdt = "getObject(LocalDateTime) unsupported";
                }
                report(
                    "timestamp " + b[0],
                    "stored="
                        + stored
                        + " getTimestamp.toInstant="
                        + viaTs
                        + (viaTs.equals(known) ? "(=known)" : "(!=known)")
                        + " getObject(LDT)="
                        + viaLdt);
              }
            } catch (SQLException e) {
              report("timestamp " + b[0], err(e));
            }
          }
          try (Statement st = c.createStatement();
              ResultSet rs =
                  st.executeQuery(
                      "SELECT SYS_EXTRACT_UTC(SYSTIMESTAMP), SYSTIMESTAMP, SESSIONTIMEZONE, DBTIMEZONE FROM DUAL")) {
            rs.next();
            LocalDateTime utcWall = rs.getTimestamp(1).toLocalDateTime();
            long skewMs =
                ChronoUnit.MILLIS.between(
                    LocalDateTime.ofInstant(Instant.now(), ZoneOffset.UTC), utcWall);
            report(
                "db_clock",
                "SYS_EXTRACT_UTC(SYSTIMESTAMP) vs JVM UTC skew(ms)="
                    + skewMs
                    + " SESSIONTIMEZONE="
                    + rs.getString(3)
                    + " DBTIMEZONE="
                    + rs.getString(4));
          }
          return null;
        });
    // OffsetDateTime 을 KST 오프셋으로 넘기면 저장 값이 바뀌는가(드라이버가 오프셋을 반영하는지).
    probe(
        "timestamp setObject(OffsetDateTime +09:00)",
        c -> {
          try (PreparedStatement ps = c.prepareStatement("UPDATE probe_t SET ts = ? WHERE v = 3")) {
            ps.setObject(1, OffsetDateTime.ofInstant(known, ZoneOffset.ofHours(9)));
            ps.executeUpdate();
          }
          try (Statement st = c.createStatement();
              ResultSet rs =
                  st.executeQuery(
                      "SELECT TO_CHAR(ts, 'YYYY-MM-DD HH24:MI:SS.FF3') FROM probe_t WHERE v = 3")) {
            rs.next();
            return "stored=" + rs.getString(1);
          }
        });
  }

  @Test
  void uuidAndNullBinding() {
    UUID u = UUID.randomUUID();
    probe(
        "uuid_setObject",
        c -> {
          try (PreparedStatement ps = c.prepareStatement("UPDATE probe_t SET s = ? WHERE v = 1")) {
            ps.setObject(1, u);
            ps.executeUpdate();
            return "OK";
          } catch (RuntimeException e) {
            // 드라이버가 SQLException 이 아닌 런타임 예외로 거절하는 경우 — 형식이 달라 err() 를 쓰지 않는다.
            return "UNSUPPORTED " + e;
          }
        });
    probe(
        "setNull_Types.OTHER",
        c -> {
          try (PreparedStatement ps = c.prepareStatement("UPDATE probe_t SET s = ? WHERE v = 1")) {
            ps.setNull(1, Types.OTHER);
            ps.executeUpdate();
            return "OK";
          }
        });
    probe(
        "setNull_Types.VARCHAR",
        c -> {
          try (PreparedStatement ps = c.prepareStatement("UPDATE probe_t SET s = ? WHERE v = 1")) {
            ps.setNull(1, Types.VARCHAR);
            ps.executeUpdate();
            return "OK";
          }
        });
    probe(
        "empty_string_is_null",
        c -> {
          try (PreparedStatement ps = c.prepareStatement("UPDATE probe_t SET s = ? WHERE v = 1")) {
            ps.setString(1, "");
            ps.executeUpdate();
          }
          try (Statement st = c.createStatement();
              ResultSet rs =
                  st.executeQuery("SELECT COUNT(*) FROM probe_t WHERE v = 1 AND s IS NULL")) {
            rs.next();
            return "rows where s IS NULL after setString('')=" + rs.getInt(1);
          }
        });
  }

