  private static String rootMessage(Throwable e) {
    Throwable t = e;
    while (t.getCause() != null) t = t.getCause();
    String m = String.valueOf(t.getMessage()).replaceAll("\\s+", " ");
    return m.length() > 160 ? m.substring(0, 160) : m;
  }
