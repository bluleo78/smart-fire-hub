  /** 이 클래스가 만드는 탐침 테이블 — 끝에서 지운다. */
  private static final List<String> PROBE_TABLES =
      List.of("probe_t", "probe_m", "probe_j", "probe_jc", "probe_clob");

  private TiberoPlatformPoc poc;

  @BeforeAll
  void start() {
    poc = TiberoPlatformPoc.shared();
    exec(
        "CREATE TABLE probe_t (id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v NUMBER(10), b NUMBER(1), s VARCHAR2(100), ts TIMESTAMP)");
    for (int i = 1; i <= 3; i++) exec("INSERT INTO probe_t (v) VALUES (" + i + ")");
  }

  /** 탐침 테이블을 지운다(만들지 못한 테이블은 건너뛴다). */
  @AfterAll
  void dropProbeTables() {
    if (poc == null) return;
    for (String t : PROBE_TABLES) {
      try {
        exec("DROP TABLE " + t);
      } catch (RuntimeException ignored) {
        // 해당 탐침이 테이블을 만들지 못했다(미지원 기록) — 지울 것이 없다.
      }
    }
  }

  private void exec(String sql) {
    poc.jdbc().execute(sql);
  }

  private static void report(String name, String result) {
    System.out.println("PROBE " + name + ": " + result);
  }

  /** 커넥션 하나로 하는 탐침 본문. 결과 문자열을 돌려주거나, 여러 줄을 스스로 남겼으면 null. */
  @FunctionalInterface
  private interface ProbeBody {
    String run(Connection c) throws SQLException;
  }

  /**
   * 풀에서 커넥션을 빌려 본문을 실행하고 {@code PROBE name: 결과} 를 남긴다. SQL 오류는 실패가 아니라 기록할 결과라 {@link #err} 로 같은
   * 이름에 남긴다.
   */
  private void probe(String name, ProbeBody body) {
    try (Connection c = poc.dataSource().getConnection()) {
      String result = body.run(c);
      if (result != null) report(name, result);
    } catch (SQLException e) {
      report(name, err(e));
    }
  }

  private static String err(SQLException e) {
    String m = e.getMessage() == null ? "" : e.getMessage().replaceAll("\\s+", " ");
    return "UNSUPPORTED code="
        + e.getErrorCode()
        + " "
        + (m.length() > 160 ? m.substring(0, 160) : m);
  }

  private List<Long> ids(Connection c, String sql, Integer maxRows) throws SQLException {
    try (Statement st = c.createStatement()) {
      if (maxRows != null) st.setMaxRows(maxRows);
      try (ResultSet rs = st.executeQuery(sql)) {
        List<Long> out = new ArrayList<>();
        while (rs.next()) out.add(rs.getLong(1));
        return out;
      }
    }
  }

