  /** 실패해야 하는 SQL 을 실행해 오류 코드를 기대값과 비교한다. */
  private void probeCode(String name, int expected, String sql) {
    try {
      exec(sql);
      report(name, "UNSUPPORTED", "statement unexpectedly succeeded");
    } catch (SQLException e) {
      boolean match = e.getErrorCode() == expected;
      report(
          name,
          String.valueOf(e.getErrorCode()),
          (match ? "matches expected " : "DIFFERS from expected ") + expected + "; " + describe(e));
    }
  }

  @Test
  void untyped_null_bind_in_merge_source() {
    String t = P + "NULLB";
    try {
      createTracked("CREATE TABLE " + t + " (ID NUMBER PRIMARY KEY, N NUMBER)", "DROP TABLE " + t);
    } catch (SQLException e) {
      unsupported("untyped_null_bind_in_merge_source", e);
      return;
    }
    String sql =
        "MERGE INTO "
            + t
            + " t USING (SELECT ? \"ID\", ? \"N\" FROM DUAL) s ON (t.ID = s.\"ID\")"
            + " WHEN MATCHED THEN UPDATE SET t.N = s.\"N\""
            + " WHEN NOT MATCHED THEN INSERT (ID, N) VALUES (s.\"ID\", s.\"N\")";
    // setNull 의 SQL 타입 힌트 세 가지를 각각 시도한다.
    int[] types = {Types.NULL, Types.NUMERIC, Types.VARCHAR};
    String[] labels = {"setNull(NULL)", "setNull(NUMERIC)", "setNull(VARCHAR)"};
    for (int i = 0; i < types.length; i++) {
      try (PreparedStatement ps = conn.prepareStatement(sql)) {
        ps.setLong(1, 100L + i);
        ps.setNull(2, types[i]);
        int count = ps.executeUpdate();
        supported("untyped_null_bind_" + labels[i], "executeUpdate=" + count);
      } catch (SQLException e) {
        unsupported("untyped_null_bind_" + labels[i], e);
      }
    }
    try (PreparedStatement ps = conn.prepareStatement(sql)) {
      ps.setLong(1, 200L);
      ps.setObject(2, null);
      supported("untyped_null_bind_setObject(null)", "executeUpdate=" + ps.executeUpdate());
    } catch (SQLException e) {
      unsupported("untyped_null_bind_setObject(null)", e);
    }
  }

