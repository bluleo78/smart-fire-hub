  /**
   * 풀({@code connectionInitSql})·DDL 직결 커넥션이 실행하는 세션 NLS 고정 익명 블록({@link
   * TiberoDialect#SESSION_INIT_SQL})이 Tibero 에서 실행되고 세 값이 실제로 바뀌는지 확인한다.
   */
  @Test
  void session_init_block() {
    try {
      exec(TiberoDialect.SESSION_INIT_SQL);
      String date = nlsSession("NLS_DATE_FORMAT");
      String ts = nlsSession("NLS_TIMESTAMP_FORMAT");
      String num = nlsSession("NLS_NUMERIC_CHARACTERS");
      boolean ok =
          "YYYY-MM-DD".equals(date) && "YYYY-MM-DD HH24:MI:SS.FF6".equals(ts) && ".,".equals(num);
      report(
          "session_init_block",
          ok ? "SUPPORTED" : "UNSUPPORTED",
          "NLS_DATE_FORMAT="
              + date
              + "; NLS_TIMESTAMP_FORMAT="
              + ts
              + "; NLS_NUMERIC_CHARACTERS="
              + num);
    } catch (SQLException e) {
      unsupported("session_init_block", e);
    }
  }

  private String nlsSession(String parameter) throws SQLException {
    return queryString(
        "SELECT VALUE FROM NLS_SESSION_PARAMETERS WHERE PARAMETER = '" + parameter + "'");
  }
