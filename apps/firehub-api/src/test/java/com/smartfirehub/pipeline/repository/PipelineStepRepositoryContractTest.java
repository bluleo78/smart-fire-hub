  @Test
  @DisplayName("findCursor·setCursor·setFullRebuildPending — 책갈피를 읽고 쓰며, 없는 스텝·다른 테넌트는 빈 값이다")
  void cursorReadWrite() {
    long ds = fx.createDataset(tenantA, prefix + "-cur");
    long id = save("cur", ds);

    StepCursor fresh = inA(() -> repository().findCursor(id)).orElseThrow();
    assertThat(fresh.lastRunAt()).isNull();
    assertThat(fresh.fullRebuildPending()).isFalse();
    assertThat(fresh.outputDatasetId()).isEqualTo(ds);
    assertThat(inA(() -> repository().findCursor(id + 1_000_000))).isEmpty();
    assertThat(inB(() -> repository().findCursor(id))).isEmpty();

    OffsetDateTime at =
        OffsetDateTime.now(ZoneOffset.UTC).minusDays(1).truncatedTo(ChronoUnit.MICROS);
    runA(() -> repository().setCursor(id, at, true));
    StepCursor set = inA(() -> repository().findCursor(id)).orElseThrow();
    assertThat(set.lastRunAt().toInstant()).isEqualTo(at.toInstant());
    assertThat(set.fullRebuildPending()).isTrue();
    assertThat(find(id).lastRunAt().toInstant()).isEqualTo(at.toInstant());

    runA(() -> repository().setFullRebuildPending(id, false));
    assertThat(inA(() -> repository().findCursor(id)).orElseThrow().fullRebuildPending()).isFalse();
    runA(() -> repository().setFullRebuildPending(id, true));
    assertThat(inA(() -> repository().findCursor(id)).orElseThrow().fullRebuildPending()).isTrue();

    runA(() -> repository().setCursor(id, null, false));
    StepCursor cleared = inA(() -> repository().findCursor(id)).orElseThrow();
    assertThat(cleared.lastRunAt()).isNull();
    assertThat(cleared.fullRebuildPending()).isFalse();
  }

  @Test
  @DisplayName("advanceCursor — 해석된 출력이 쓴 출력과 같을 때만 전진하고, 전체 재생성이었으면 예약을 끈다")
  void advanceCursor_guardedByResolvedOutput() {
    long ds = fx.createDataset(tenantA, prefix + "-adv");
    long ds2 = fx.createDataset(tenantA, prefix + "-adv2");
    long pinned = save("pinned", ds);
    long auto = save("auto", null);
    long temp = tempDataset(auto, prefix + "-adv-temp");
    long bare = save("bare", null);
    OffsetDateTime at =
        OffsetDateTime.now(ZoneOffset.UTC).minusHours(2).truncatedTo(ChronoUnit.MICROS);

    // 지정 출력: 같은 출력이면 전진, 다르면(출력이 바뀐 경우) 그대로.
    runA(() -> repository().advanceCursor(pinned, at, false, ds2));
    assertThat(inA(() -> repository().findCursor(pinned)).orElseThrow().lastRunAt()).isNull();
    runA(() -> repository().advanceCursor(pinned, at, false, null));
    assertThat(inA(() -> repository().findCursor(pinned)).orElseThrow().lastRunAt()).isNull();
    runA(() -> repository().advanceCursor(pinned, at, false, ds));
    assertThat(inA(() -> repository().findCursor(pinned)).orElseThrow().lastRunAt().toInstant())
        .isEqualTo(at.toInstant());

    // 자동 TEMP 출력: 해석된 TEMP id 로 전진한다.
    runA(() -> repository().setFullRebuildPending(auto, true));
    runA(() -> repository().advanceCursor(auto, at, false, temp));
    StepCursor kept = inA(() -> repository().findCursor(auto)).orElseThrow();
    assertThat(kept.lastRunAt().toInstant()).isEqualTo(at.toInstant());
    assertThat(kept.fullRebuildPending()).as("전체 재생성이 아니면 예약을 건드리지 않는다").isTrue();
    runA(() -> repository().advanceCursor(auto, at.plusHours(1), true, temp));
    StepCursor done = inA(() -> repository().findCursor(auto)).orElseThrow();
    assertThat(done.lastRunAt().toInstant()).isEqualTo(at.plusHours(1).toInstant());
    assertThat(done.fullRebuildPending()).isFalse();

    // 출력이 아직 없는 스텝(해석된 출력 null)은 쓴 출력이 null 일 때만 전진한다.
    runA(() -> repository().advanceCursor(bare, at, false, ds));
    assertThat(inA(() -> repository().findCursor(bare)).orElseThrow().lastRunAt()).isNull();
    runA(() -> repository().advanceCursor(bare, at, false, null));
    assertThat(inA(() -> repository().findCursor(bare)).orElseThrow().lastRunAt().toInstant())
        .isEqualTo(at.toInstant());

    // 다른 테넌트·없는 스텝은 아무 일도 없다.
    runB(() -> repository().advanceCursor(pinned, at.minusDays(1), false, ds));
    runA(() -> repository().advanceCursor(pinned + 1_000_000, at, false, null));
    assertThat(inA(() -> repository().findCursor(pinned)).orElseThrow().lastRunAt().toInstant())
        .isEqualTo(at.toInstant());
  }

  /** 테넌트 B 범위에서 결과 없는 호출을 실행한다. */
  private void runB(Runnable call) {
    inB(
        () -> {
          call.run();
          return null;
        });
  }
