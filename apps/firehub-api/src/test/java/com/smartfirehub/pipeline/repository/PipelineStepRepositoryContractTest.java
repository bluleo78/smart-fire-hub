  @Test
  @DisplayName("findByPipelineId — 출력 데이터셋 이름만 가리고 id 는 남기며, 지정 출력이 없으면 러너 TEMP 로 풀어 자동 생성으로 본다")
  void findByPipelineId_masksNameAndResolvesTemp() {
    long secretLevel = fx.createSecurityLevel(tenantA, 5, prefix + "-secret");
    long open = fx.createDataset(tenantA, prefix + "-open");
    long secret = fx.createDataset(tenantA, prefix + "-secret");
    fx.setDatasetField(secret, "security_level_id", secretLevel);
    long openStep = save("open", open);
    long secretStep = save("secret", secret);
    long autoStep = save("auto", null);
    long temp = tempDataset(autoStep, prefix + "-temp");
    long pinnedStep = save("pinned", null);
    long pinnedTemp = tempDataset(pinnedStep, prefix + "-pinned");
    // 화면 저장이 해석된 TEMP id 를 명시 출력으로 고정한 스텝도 자동 생성으로 본다(WD-222).
    runA(
        () ->
            repository()
                .updateStep(pipeline, pinnedStep, sql("pinned", "select 1", pinnedTemp), 0));
    long noneStep = save("none", null);

    List<PipelineStepResponse> low = inA(() -> repository().findByPipelineId(pipeline, rank(2)));
    assertThat(low).hasSize(5);
    PipelineStepResponse sOpen = byId(low, openStep);
    assertThat(sOpen.outputDatasetName()).isEqualTo(prefix + "-open");
    assertThat(sOpen.outputAutoGenerated()).isFalse();
    PipelineStepResponse sSecret = byId(low, secretStep);
    assertThat(sSecret.outputDatasetId()).isEqualTo(secret);
    assertThat(sSecret.outputDatasetName()).as("안 보이는 등급의 이름은 가리고 id 는 남긴다").isNull();
    PipelineStepResponse sAuto = byId(low, autoStep);
    assertThat(sAuto.outputDatasetId()).isEqualTo(temp);
    assertThat(sAuto.outputDatasetName()).isEqualTo(prefix + "-temp");
    assertThat(sAuto.outputAutoGenerated()).isTrue();
    PipelineStepResponse sPinned = byId(low, pinnedStep);
    assertThat(sPinned.outputDatasetId()).isEqualTo(pinnedTemp);
    assertThat(sPinned.outputAutoGenerated()).isTrue();
    PipelineStepResponse sNone = byId(low, noneStep);
    assertThat(sNone.outputDatasetId()).isNull();
    assertThat(sNone.outputDatasetName()).isNull();
    assertThat(sNone.outputAutoGenerated()).isTrue();

    List<PipelineStepResponse> high = inA(() -> repository().findByPipelineId(pipeline, rank(5)));
    assertThat(byId(high, secretStep).outputDatasetName()).isEqualTo(prefix + "-secret");
    List<PipelineStepResponse> all = inA(() -> repository().findByPipelineId(pipeline));
    assertThat(byId(all, secretStep).outputDatasetName()).isEqualTo(prefix + "-secret");
    List<PipelineStepResponse> none =
        inA(
            () ->
                repository()
                    .findByPipelineId(
                        pipeline, new DatasetVisibility(Clearance.none(user, tenantA), null)));
    assertThat(none).extracting(PipelineStepResponse::outputDatasetName).containsOnlyNulls();
    assertThat(byId(none, secretStep).outputDatasetId()).isEqualTo(secret);
    assertThat(inB(() -> repository().findByPipelineId(pipeline))).isEmpty();
  }

  private static PipelineStepResponse byId(List<PipelineStepResponse> list, long id) {
    return list.stream().filter(s -> s.id() == id).findFirst().orElseThrow();
  }

