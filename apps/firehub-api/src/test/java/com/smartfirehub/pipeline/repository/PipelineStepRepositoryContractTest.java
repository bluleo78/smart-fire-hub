  @Test
  @DisplayName(
      "findTempDatasetIdsByStepIds·findTempOwnerStepIdsByDatasetIds·findAutoTempDatasetIdsByStepIds — TEMP 매핑을 양방향으로 읽는다")
  void tempLookups() {
    long a = save("a", null);
    long b = save("b", null);
    long c = save("c", null);
    long tempA = tempDataset(a, prefix + "-ta");
    long tempB = tempDataset(b, prefix + "-tb");
    // 출처 스텝은 있지만 TEMP 가 아닌 데이터셋(DERIVED) — 자동 TEMP·소유 매핑에서 빠지고 스텝 → 데이터셋 매핑에는 든다.
    long derived = fx.createDataset(tenantA, prefix + "-der");
    fx.setDatasetField(derived, "origin_type", "DERIVED");
    fx.setDatasetField(derived, "source_pipeline_step_id", c);
    long plain = fx.createDataset(tenantA, prefix + "-plain");

    assertThat(inA(() -> repository().findTempDatasetIdsByStepIds(List.of()))).isEmpty();
    assertThat(inA(() -> repository().findTempDatasetIdsByStepIds(List.of(a, b, c))))
        .containsOnly(Map.entry(a, tempA), Map.entry(b, tempB), Map.entry(c, derived));
    assertThat(inA(() -> repository().findTempOwnerStepIdsByDatasetIds(List.of()))).isEmpty();
    assertThat(
            inA(
                () ->
                    repository()
                        .findTempOwnerStepIdsByDatasetIds(List.of(tempA, tempB, derived, plain))))
        .containsOnly(Map.entry(tempA, a), Map.entry(tempB, b));
    assertThat(inA(() -> repository().findAutoTempDatasetIdsByStepIds(List.of()))).isEmpty();
    assertThat(inA(() -> repository().findAutoTempDatasetIdsByStepIds(List.of(a, b, c))))
        .containsExactly(Math.min(tempA, tempB), Math.max(tempA, tempB));
    assertThat(inB(() -> repository().findAutoTempDatasetIdsByStepIds(List.of(a, b, c)))).isEmpty();
    assertThat(inB(() -> repository().findTempDatasetIdsByStepIds(List.of(a)))).isEmpty();
  }

