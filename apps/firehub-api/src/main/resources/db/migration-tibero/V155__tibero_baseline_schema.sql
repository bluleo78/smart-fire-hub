-- Tibero 플랫폼 DB 기준선 — 스키마(WD-490, ADR 0001 결정 2)
--
-- 무엇을: PG 마이그레이션 V1~V155(+Java V125)를 다 적용한 public 스키마를 Tibero DDL 한 파일로 옮겼다. Tibero 설치본은 이 파일부터
--   시작한다(V1~V154 는 Tibero 쪽에 없다). 시드 행은 DML 을 DDL 과 섞지 않는 규칙대로 V155.1 에 따로 둔다.
-- 이후 규칙: PG 에 Vn(n > 155)을 추가하면 이 폴더에도 같은 버전 Vn 을 둔다. Tibero 에 할 일이 없으면 주석만 있는 파일을 둔다.
--   MigrationParityTest 가 두 폴더의 버전 집합을 대조한다. 새 파일은 1파일 1DDL(여러 DDL 이면 사전 뷰로 존재 확인 + EXECUTE IMMEDIATE 멱등 블록),
--   DML 은 DDL 과 다른 파일 — Tibero DDL 은 암묵 커밋이라 실패하면 반쯤 적용된 객체가 남는다(WD-488 실측).
-- 새 설치는 빈 계정에서 시작한다(Tibero 프로필은 baseline-on-migrate=false). 기준선 실패 복구: 스키마(계정)를 비우고 처음부터 다시
--   적용한다. 이 파일은 멱등이 아니다.
-- 구조 검사: TiberoBaselineSchemaLiveTest 가 PG(jOOQ 생성 테이블)의 테이블·열이 아래 제외 목록을 빼고 모두 있는지 Tibero 실서버에서 본다.
--
-- 타입 대응(PG → Tibero):
--   bigint/integer → NUMBER(19)/NUMBER(10), boolean → NUMBER(1) + CHECK (0, 1), double precision → BINARY_DOUBLE, numeric(p,s) → NUMBER(p,s)
--   varchar(n) → VARCHAR2(n CHAR) — PG 의 n 은 글자 수라 바이트 단위로 두면 한글이 잘린다(-11048)
--   text → VARCHAR2(65532)(바이트), 인덱스·유니크에 쓰이는 text 는 VARCHAR2(1000 CHAR)(키 길이 한도),
--     큰 본문(pipeline_step.script_content, pipeline_step_execution.log)만 CLOB — CLOB 은 GROUP BY·DISTINCT·인덱스 불가
--   jsonb → JSON, uuid → VARCHAR2(36)(드라이버가 setObject(UUID) 를 못 받음, WD-487), serial/bigserial → GENERATED BY DEFAULT AS IDENTITY
--   timestamptz → TIMESTAMP(UTC 벽시계, DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP)) — TSTZ 열은 색인 + AT TIME ZONE 결함(WD-260) 때문에 쓰지 않는다
--   timestamp → TIMESTAMP(DEFAULT LOCALTIMESTAMP = 세션 시간대 벽시계, PG 의 now() 와 같은 기준. 설치본 JVM 은 UTC 강제 — WD-496)
--   gen_random_uuid() → SYS_GUID() 를 8-4-4-4-12 소문자로 바꾼 DEFAULT
--   시드가 ID 를 명시로 넣는 테이블은 IDENTITY 를 시드 최대 ID 다음부터 시작한다(첫 앱 INSERT 가 유일 위반 -10007 이 나지 않게).
--   예약어 이름(USER 테이블, RESOURCE 열)은 큰따옴표 대문자로 만든다 — SQL 에서도 "USER"·"RESOURCE" 로 부른다.
--
-- 모양이 바뀐 것:
--   부분 인덱스(WHERE) — 일반 인덱스는 WHERE 없는 전체 인덱스로(결과는 같고 크기만 크다. CASE 함수 기반으로 두면 질의가 같은 식을 써야만 타므로
--     지금 질의가 그대로 쓰는 전체 인덱스를 골랐다), UNIQUE 는 CASE WHEN 조건 THEN 열 END 함수 기반 인덱스로(모든 키가 NULL 인 행은 색인되지 않으므로
--     조건 밖 행은 유일 검사에서 빠진다).
--   NULL 일 수 있는 열이 낀 다열 UNIQUE — PG 는 키에 NULL 이 하나라도 있으면 검사하지 않지만, Tibero 는 NULL 아닌 열끼리 같으면 충돌한다.
--     그래서 "모든 키 열이 NOT NULL 일 때만" 키를 만드는 CASE 함수 기반 UNIQUE 인덱스로 바꿨다(이름은 PG 제약·인덱스 이름 그대로):
--     uq_dataset_access_grant_role·_user(사용자 XOR 역할), uk_user_channel(EMAIL·KAKAO 는 workspace_id NULL),
--     uk_ai_session_slack_thread, uq_document_file_dataset_checksum. PG 에서 제약이던 앞의 셋은 Tibero 에서는 인덱스다.
--   NULLS NOT DISTINCT(uq_graph_review_item) → NVL(dataset_id, -1) 함수 기반 UNIQUE(WD-487 PoC 와 같은 모양)
--   같은 열 목록의 인덱스는 하나만 둔다(Tibero -7124): idx_user_username(user_username_key 와 같음),
--     idx_api_connection_tenant_healthcheck·idx_async_job_active(부분 → 전체로 바꾸면 기존 인덱스와 같은 열)
--   INCLUDE 열(idx_outbox_pending_tenant_due) — 뺐다. 외래 키 — 순환(dataset ↔ pipeline_step)이 있어 테이블을 다 만든 뒤 ALTER TABLE 로 붙인다.
--   DEFAULT '' (''=NULL): dataset_search_index.config_hash, proactive_job.prompt 는 NOT NULL 을 풀고 기본값을 뺐다.
--     앱이 '' 를 넣을 수 있는 NOT NULL text(검증이 null 만 막는다) — ontology_entity_type.description·naming, ontology_relation.description,
--     ontology_entity_property.description 도 NOT NULL 을 풀었다.
--     코드가 '' 를 쓰는 곳(재색인 강제 표시 등)을 NULL 로 읽게 하고 나머지 NOT NULL 열에 '' 를 쓰는 곳을 점검하는 일은 각 리포지토리 MyBatis
--     구현(WD-491)이 맡는다 — 구조 검사(TiberoBaselineSchemaLiveTest)의 NULL 허용 차이 허용 목록이 이 열들이다.
--
-- 제외 목록(기준선에 없음 — 맡은 이슈):
--   테이블 dataset_embedding_vec_1024·1536, document_chunk_vec_1024·1536(VECTOR 타입)과 HNSW·trigram(GIN) 인덱스 → WD-495(벡터·키워드 검색 비활성)
--   spatial_ref_sys(PostGIS 확장) — 플랫폼 DB 에 공간 기능 없음(공간은 데이터 저장소 기능)
--   RLS 정책 61개, tenant_id 열의 DEFAULT current_setting('app.tenant_id')(62개), GRANT·런타임 롤 → WD-492(CONTEXT + DBMS_RLS)
--     그래서 지금은 tenant_id 를 문장이 명시로 넣어야 한다(NOT NULL).
--   함수 resolve_trigger_tenant_by_token_hash·resolve_trigger_tenant_by_webhook_id·resolve_slack_workspace_tenant_by_team_id·
--     outbox_tenant_ids·proactive_active_execution_tenant_ids(RLS 우회 조회), tenant_default_security_level_id(DEFAULT 2곳),
--     provision_tenant_defaults(테넌트 기본값 생성) → WD-492
--   함수 fh_touch_updated_at·fh_incremental_cursor_candidate(data 스키마 데이터셋 테이블용) → WD-494(데이터 저장소 분리)
--   JobRunr 테이블은 PG V85 를 옮기지 않고 JobRunr 7.3.2 jar 의 Oracle 스크립트(v000~v015) 최종 모양을 맨 끝에 둔다.
--     org.jobrunr.database.skip-create=true 라 런타임은 DDL 을 하지 않는다(PG 와 같음). JobRunr 를 올리면 이 부분도 맞춘다.

