-- V128: 플랫폼 설정에서 SMTP 설정을 완전히 없앤다(#712, 2026-09-23).
--
-- SMTP 6키(smtp.host/port/username/password/starttls/from_address)는 이제 워크스페이스(테넌트) 전용이다.
--   - 발송 경로(SettingsService.getSmtpConfig)는 tenant_settings 의 값만 읽는다.
--     값이 없으면 미설정이고, 알림·리포트 메일은 "워크스페이스 설정 › 이메일에서 등록하라"는
--     오류로 실패한다. 테넌트 컨텍스트가 없는 호출도 미설정이다(플랫폼 폴백 없음).
--   - 플랫폼 설정 API 는 smtp.* 를 내보내지 않고(GET), 쓰기를 400 으로 거부한다(PUT).
-- 그래서 system_settings 의 smtp.* 행은 읽는 곳이 없다. #706 이 ai.* 에 한 것(V126/V127)과 같은 정리다.
--
-- 예전에는 플랫폼 기본값 + 워크스페이스 값의 두 평면이었고, 연결 5키가 섞이지 않게 하는 "원자 해석"
-- 규칙과 화면의 상속·해제 표시가 그 위에 얹혀 있었다. 평면이 하나가 되면서 그 규칙이 통째로 사라진다.
--
-- 플랫폼 값을 워크스페이스로 복사하지 않는다 — 의도다(사용자 결정 2026-09-23). 공용 SMTP 계정의
-- 자격증명을 모든 워크스페이스 행으로 퍼뜨리면 "누가 이 계정을 쓰는가"가 흐려지고, 미설정 상태를
-- 명확한 오류로 드러내려는 목적과도 어긋난다. 배포 전에 운영 값을 기록해 두고, 필요한 워크스페이스는
-- 자기 설정 화면에서 다시 등록한다(.claude/docs/deploy.md 의 V128 배포 노트 참고).
--
-- tenant_settings 의 smtp.* 행(각 워크스페이스가 저장한 값)은 건드리지 않는다.
-- 멱등: 행이 없으면 0행 삭제다(V42 시드가 없는 환경에서도 무해).

DELETE FROM system_settings WHERE key LIKE 'smtp.%';
