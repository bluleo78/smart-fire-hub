-- WD-155: 데이터셋 이름의 유일 범위를 「테넌트 전체」에서 「조회자가 볼 수 있는 데이터셋」으로 좁힌다.
--
-- 왜: (tenant_id, name) 유일 인덱스가 있으면, 볼 수 없는(상위 등급) 데이터셋과 같은 이름으로 만들거나 바꿀 때 409 가 나서
-- 이름을 맞혀 보는 것만으로 숨긴 데이터셋의 존재가 드러났다(WD-35 「존재조차 보이지 않길」, 스펙 §2.5 존재 은닉 위반).
-- 결정(2026-10-22, WD-155 B안): 이름 중복 검사는 앱(DatasetService)이 조회자의 가시 범위 안에서만 하고, DB 유일 제약은 없앤다.
-- 그래서 등급이 다른 같은 이름 데이터셋이 둘 있을 수 있다(관리자 목록에는 둘 다 보인다).
--
-- table_name 은 data 스키마의 물리 테이블 이름이라 (tenant_id, table_name) 유일 인덱스(V112)를 그대로 둔다 — 테이블명
-- 충돌은 문구만 일반화하고 「알려진 한계」로 문서화한다(deploy.md).
--
-- 조회 성능: 이름 검색·중복 검사가 쓰던 인덱스는 같은 컬럼의 일반 인덱스로 남긴다.
-- 롤백 주의: 이 마이그레이션 뒤 같은 이름 데이터셋이 생기면 유일 인덱스를 다시 만들 수 없다 — DB 는 되돌리지 않는다.

DROP INDEX IF EXISTS idx_dataset_name;
CREATE INDEX idx_dataset_name ON dataset (tenant_id, name);
