-- V152: 대시보드 자동 새로고침 주기를 24시간(86400초) 상한으로 맞춘다 (WD-327).
--
-- 왜 필요한가: 상한 검증(@Max 86400)을 넣기 전에는 2500000초 같은 값이 그대로 저장됐다. 이런 값은 브라우저 타이머
-- 지연(2^31 ms ≈ 24.8일)을 넘어 0 으로 감겨 위젯 데이터를 쉬지 않고 다시 요청했고, 이제는 설정 창에서 다른 항목만
-- 바꿔 저장해도 상한 검증에 걸려 저장되지 않는다. 사용자가 고른 "아주 드물게 새로고침" 의도에 가장 가까운 상한값으로
-- 바꿔 두어, 목록·편집 배지·신선도 표시·AI 에이전트가 모두 실제로 쓰는 주기를 보게 한다.
UPDATE dashboard
SET auto_refresh_seconds = 86400
WHERE auto_refresh_seconds > 86400;
