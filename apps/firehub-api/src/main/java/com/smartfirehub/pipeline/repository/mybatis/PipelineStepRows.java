package com.smartfirehub.pipeline.repository.mybatis;

import com.smartfirehub.global.platformdb.mybatis.GeneratedId;
import java.time.Instant;

/** PipelineStepMapper 의 평평한 행·INSERT 홀더 모음(WD-708). */
public final class PipelineStepRows {

  private PipelineStepRows() {}

  /**
   * 스텝 한 줄(화면 응답용). JSON 설정 3종은 문자열 그대로(구현이 Map 으로 푼다). 시각은 UTC 순간(Tibero 는 UTC 벽시계 TIMESTAMP 라
   * 핸들러가 맞춘다). 출력 데이터셋 이름은 조회자가 볼 수 없으면 null.
   */
  public record StepRow(
      Long id,
      String name,
      String description,
      String scriptType,
      String scriptContent,
      Long resolvedOutputDatasetId,
      boolean outputAutoGenerated,
      int stepOrder,
      String loadStrategy,
      String apiConfig,
      String aiConfig,
      String pythonConfig,
      Long apiConnectionId,
      Instant lastRunAt,
      boolean fullRebuildPending,
      String outputDatasetName) {}

  /** 스텝 입력 데이터셋 한 줄. */
  public record InputRow(Long stepId, Long datasetId) {}

  /** 스텝 의존 한 줄 — 의존 대상 스텝의 이름으로 풀려 있다. */
  public record DependencyRow(Long stepId, String dependsOnStepName) {}

  /** 두 id 쌍(데이터셋 ↔ 스텝 매핑용). */
  public record IdPair(Long first, Long second) {}

  /** 증분 책갈피 행. */
  public record CursorRow(Instant lastRunAt, boolean fullRebuildPending, Long outputDatasetId) {}

  /**
   * 스텝 INSERT 파라미터 겸 생성 키 홀더. Tibero 에는 RETURNING 이 없어 JDBC 생성 키가 {@code id} 에 써 넣는다. JSON 설정은 이미
   * 직렬화된 문자열(null 이면 NULL).
   */
  public static class StepInsert extends GeneratedId {
    private final Long pipelineId;
    private final String name;
    private final String description;
    private final String scriptType;
    private final String scriptContent;
    private final Long outputDatasetId;
    private final int stepOrder;
    private final String loadStrategy;
    private final String apiConfig;
    private final String aiConfig;
    private final String pythonConfig;
    private final Long apiConnectionId;

    public StepInsert(
        Long pipelineId,
        String name,
        String description,
        String scriptType,
        String scriptContent,
        Long outputDatasetId,
        int stepOrder,
        String loadStrategy,
        String apiConfig,
        String aiConfig,
        String pythonConfig,
        Long apiConnectionId) {
      this.pipelineId = pipelineId;
      this.name = name;
      this.description = description;
      this.scriptType = scriptType;
      this.scriptContent = scriptContent;
      this.outputDatasetId = outputDatasetId;
      this.stepOrder = stepOrder;
      this.loadStrategy = loadStrategy;
      this.apiConfig = apiConfig;
      this.aiConfig = aiConfig;
      this.pythonConfig = pythonConfig;
      this.apiConnectionId = apiConnectionId;
    }

    public Long getPipelineId() {
      return pipelineId;
    }

    public String getName() {
      return name;
    }

    public String getDescription() {
      return description;
    }

    public String getScriptType() {
      return scriptType;
    }

    public String getScriptContent() {
      return scriptContent;
    }

    public Long getOutputDatasetId() {
      return outputDatasetId;
    }

    public int getStepOrder() {
      return stepOrder;
    }

    public String getLoadStrategy() {
      return loadStrategy;
    }

    public String getApiConfig() {
      return apiConfig;
    }

    public String getAiConfig() {
      return aiConfig;
    }

    public String getPythonConfig() {
      return pythonConfig;
    }

    public Long getApiConnectionId() {
      return apiConnectionId;
    }
  }
}
