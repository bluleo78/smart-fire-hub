package com.smartfirehub.pipeline.repository.mybatis;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.smartfirehub.global.platformdb.mybatis.InChunks;
import com.smartfirehub.global.platformdb.mybatis.PlatformJson;
import com.smartfirehub.global.platformdb.mybatis.PlatformMyBatisRepository;
import com.smartfirehub.pipeline.dto.PipelineStepRequest;
import com.smartfirehub.pipeline.dto.PipelineStepResponse;
import com.smartfirehub.pipeline.dto.StepCursor;
import com.smartfirehub.pipeline.repository.PipelineStepRepository;
import com.smartfirehub.pipeline.repository.mybatis.PipelineStepRows.CursorRow;
import com.smartfirehub.pipeline.repository.mybatis.PipelineStepRows.IdPair;
import com.smartfirehub.pipeline.repository.mybatis.PipelineStepRows.StepInsert;
import com.smartfirehub.pipeline.repository.mybatis.PipelineStepRows.StepRow;
import com.smartfirehub.securitylevel.access.DatasetVisibility;
import com.smartfirehub.securitylevel.repository.mybatis.MyBatisDatasetVisibility;
import java.time.Instant;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.Collection;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import org.springframework.transaction.annotation.Transactional;

/**
 * PipelineStepRepository 의 MyBatis 구현(WD-708) — {@code JooqPipelineStepRepository} 와 같은 의미.
 *
 * <p>트랜잭션 속성은 jOOQ 구현 그대로 클래스 단위 plain {@code @Transactional} 이다 — 배경 잡은 앰비언트 트랜잭션이 없고, 트랜잭션이 없으면
 * 테넌트 컨텍스트가 심기지 않아 정책이 0행이 된다.
 *
 * <p>스텝 컬렉션 메서드(입력·의존·TEMP 매핑·삭제)의 id 목록은 {@link InChunks} 로 500 개씩 나눠 한 문장에 OR 로 잇는다 — Tibero IN
 * 목록 상한(1000) 대응이다. JSON 설정 3종은 문자열로 주고받고 Map 변환은 여기서 한다. 시각 열은 UTC 순간(Instant)으로 오가고 응답에서만 UTC 오프셋
 * 시각으로 감싼다.
 */
@PlatformMyBatisRepository
@Transactional
@lombok.extern.slf4j.Slf4j
public class MyBatisPipelineStepRepository implements PipelineStepRepository {

  /** 이름을 바꿀 스텝을 잠시 비켜 두는 임시 이름의 접두사(jOOQ 판과 같다). */
  private static final String RENAMING_PLACEHOLDER_PREFIX = "__renaming_";

  /** 적재 전략이 비었을 때의 기본값(jOOQ 판과 같다) — 저장·응답 양쪽이 쓴다. */
  private static final String DEFAULT_LOAD_STRATEGY = "REPLACE";

  private final PipelineStepMapper mapper;
  private final ObjectMapper objectMapper;

  public MyBatisPipelineStepRepository(PipelineStepMapper mapper, ObjectMapper objectMapper) {
    this.mapper = mapper;
    this.objectMapper = objectMapper;
  }

  @Override
  public List<PipelineStepResponse> findByPipelineId(Long pipelineId) {
    return findByPipelineId(pipelineId, DatasetVisibility.UNRESTRICTED);
  }

  @Override
  public List<PipelineStepResponse> findByPipelineId(
      Long pipelineId, DatasetVisibility outputNameVisibility) {
    List<StepRow> steps =
        mapper.selectSteps(pipelineId, MyBatisDatasetVisibility.params(outputNameVisibility));
    if (steps.isEmpty()) {
      return List.of();
    }
    List<List<Long>> chunks = InChunks.of(steps.stream().map(StepRow::id).toList());

    // 입력 데이터셋·의존(의존 대상 스텝 이름) — 스텝 id 별로 모은다.
    Map<Long, List<Long>> inputMap = new HashMap<>();
    mapper
        .selectInputs(chunks)
        .forEach(
            r -> inputMap.computeIfAbsent(r.stepId(), k -> new ArrayList<>()).add(r.datasetId()));
    Map<Long, List<String>> dependencyMap = new HashMap<>();
    mapper
        .selectDependencies(chunks)
        .forEach(
            r ->
                dependencyMap
                    .computeIfAbsent(r.stepId(), k -> new ArrayList<>())
                    .add(r.dependsOnStepName()));

    return steps.stream()
        .map(
            r ->
                new PipelineStepResponse(
                    r.id(),
                    r.name(),
                    r.description(),
                    r.scriptType(),
                    r.scriptContent(),
                    r.resolvedOutputDatasetId(),
                    r.outputDatasetName(),
                    inputMap.getOrDefault(r.id(), List.of()),
                    dependencyMap.getOrDefault(r.id(), List.of()),
                    r.stepOrder(),
                    r.loadStrategy() != null ? r.loadStrategy() : DEFAULT_LOAD_STRATEGY,
                    parseConfig(r.apiConfig(), "api_config"),
                    parseConfig(r.aiConfig(), "ai_config"),
                    parseConfig(r.pythonConfig(), "python_config"),
                    r.apiConnectionId(),
                    toOffset(r.lastRunAt()),
                    r.fullRebuildPending(),
                    // 경고/재생성 모드는 SQL 구조 분석이 필요해 리포지토리 책임이 아니다 — 서비스가 붙인다.
                    List.of(),
                    null,
                    r.outputAutoGenerated()))
        .toList();
  }

  @Override
  public Long saveStep(Long pipelineId, PipelineStepRequest request, int stepOrder) {
    StepInsert row = toInsert(pipelineId, request, stepOrder);
    mapper.insert(row);
    return row.getId();
  }

  @Override
  public void updateStep(Long pipelineId, Long stepId, PipelineStepRequest request, int stepOrder) {
    mapper.update(pipelineId, stepId, toInsert(pipelineId, request, stepOrder));
  }

  @Override
  public void renameStepTemporarily(Long pipelineId, Long stepId) {
    mapper.renameTemporarily(pipelineId, stepId, RENAMING_PLACEHOLDER_PREFIX + stepId);
  }

  @Override
  public void saveStepInput(Long stepId, Long datasetId) {
    mapper.insertInput(stepId, datasetId);
  }

  @Override
  public void saveStepDependency(Long stepId, Long dependsOnStepId) {
    mapper.insertDependency(stepId, dependsOnStepId);
  }

  @Override
  public void deleteByPipelineId(Long pipelineId) {
    deleteSteps(pipelineId, mapper.selectStepIdsByPipeline(pipelineId));
  }

  @Override
  public void deleteSteps(Long pipelineId, Collection<Long> stepIds) {
    if (stepIds.isEmpty()) {
      return;
    }
    clearInputsAndDependencies(stepIds);
    mapper.deleteSteps(pipelineId, InChunks.of(stepIds));
  }

  @Override
  public void clearInputsAndDependencies(Collection<Long> stepIds) {
    if (stepIds.isEmpty()) {
      return;
    }
    List<List<Long>> chunks = InChunks.of(stepIds);
    mapper.deleteDependencies(chunks);
    mapper.deleteInputs(chunks);
  }

  @Override
  public Map<Long, Long> findTempDatasetIdsByStepIds(Collection<Long> stepIds) {
    Map<Long, Long> result = new HashMap<>();
    if (stepIds.isEmpty()) {
      return result;
    }
    // 한 스텝에 TEMP 가 여럿이면 id 가 가장 작은 것(쿼리가 id 순) — 처음 나온 값을 지킨다.
    for (IdPair p : mapper.selectTempDatasetsByStepIds(InChunks.of(stepIds))) {
      result.putIfAbsent(p.first(), p.second());
    }
    return result;
  }

  @Override
  public Map<Long, Long> findTempOwnerStepIdsByDatasetIds(Collection<Long> datasetIds) {
    Map<Long, Long> result = new HashMap<>();
    if (datasetIds.isEmpty()) {
      return result;
    }
    for (IdPair p : mapper.selectTempOwnersByDatasetIds(InChunks.of(datasetIds))) {
      result.put(p.first(), p.second());
    }
    return result;
  }

  @Override
  public List<Long> findAutoTempDatasetIdsByStepIds(Collection<Long> stepIds) {
    if (stepIds.isEmpty()) {
      return List.of();
    }
    // 조각이 여럿이어도 한 문장(OR)의 ORDER BY d.id 라 전체 id 오름차순이다.
    return mapper.selectAutoTempDatasetIds(InChunks.of(stepIds));
  }

  @Override
  public Set<Long> findDatasetIdsUsedAsOutputExcludingSteps(
      Collection<Long> datasetIds, Collection<Long> excludedStepIds) {
    if (datasetIds.isEmpty()) {
      return Set.of();
    }
    return new HashSet<>(
        mapper.selectUsedOutputDatasetIds(InChunks.of(datasetIds), InChunks.of(excludedStepIds)));
  }

  @Override
  public List<Long> findStepIdsByPipelineId(Long pipelineId) {
    return mapper.selectStepIdsByPipeline(pipelineId);
  }

  @Override
  public Optional<StepCursor> findCursor(Long stepId) {
    CursorRow r = mapper.selectCursor(stepId);
    if (r == null) {
      return Optional.empty();
    }
    return Optional.of(
        new StepCursor(toOffset(r.lastRunAt()), r.fullRebuildPending(), r.outputDatasetId()));
  }

  @Override
  public void advanceCursor(
      Long stepId, OffsetDateTime candidate, boolean wasFullRebuild, Long writtenOutputDatasetId) {
    int updated =
        mapper.advanceCursor(stepId, toInstant(candidate), wasFullRebuild, writtenOutputDatasetId);
    if (updated == 0) {
      log.warn("스텝 {} 의 출력이 실행 도중 바뀌었거나 스텝이 지워져 증분 책갈피를 전진시키지 않습니다(다음 실행이 해당 구간을 다시 읽습니다)", stepId);
    }
  }

  @Override
  public void setFullRebuildPending(Long stepId, boolean pending) {
    mapper.setFullRebuildPending(stepId, pending);
  }

  @Override
  public void setCursor(Long stepId, OffsetDateTime lastRunAt, boolean pending) {
    mapper.setCursor(stepId, toInstant(lastRunAt), pending);
  }

  @Override
  public Optional<Long> findStepIdByPipelineAndName(Long pipelineId, String name) {
    return Optional.ofNullable(mapper.selectStepIdByPipelineAndName(pipelineId, name));
  }

  /** 요청을 INSERT·UPDATE 파라미터로 바꾼다 — 적재 전략 기본값 REPLACE, JSON 설정은 직렬화. */
  private StepInsert toInsert(Long pipelineId, PipelineStepRequest request, int stepOrder) {
    return new StepInsert(
        pipelineId,
        request.name(),
        request.description(),
        request.scriptType(),
        request.scriptContent(),
        request.outputDatasetId(),
        stepOrder,
        request.loadStrategy() != null ? request.loadStrategy() : DEFAULT_LOAD_STRATEGY,
        toJson(request.apiConfig(), "apiConfig"),
        toJson(request.aiConfig(), "aiConfig"),
        toJson(request.pythonConfig(), "pythonConfig"),
        request.apiConnectionId());
  }

  /** DB 의 UTC 순간 → 응답용 UTC 오프셋 시각. */
  private static OffsetDateTime toOffset(Instant at) {
    return at == null ? null : at.atOffset(ZoneOffset.UTC);
  }

  /** 요청의 오프셋 시각 → 바인딩할 UTC 순간(toOffset 의 반대). */
  private static Instant toInstant(OffsetDateTime at) {
    return at == null ? null : at.toInstant();
  }

  /** 맵 설정값을 JSON 문자열로 직렬화한다 — null 은 null, 실패는 SerializationException(jOOQ 판과 같다). */
  private String toJson(Map<String, Object> value, String label) {
    return PlatformJson.write(objectMapper, value, label);
  }

  /** JSON 문자열을 맵으로 푼다 — null·빈 값은 null, 깨진 JSON 은 SerializationException(jOOQ 판과 같다). */
  private Map<String, Object> parseConfig(String json, String column) {
    return json == null || json.isEmpty() ? null : PlatformJson.toMap(objectMapper, json, column);
  }
}
